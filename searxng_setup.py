def cmd_install(paths, port, explicit_port, autostart, update=False):
    say("SearXNG for srchplex: %s, http://127.0.0.1:%d" % (paths.root, port))
    _check_folder(paths)
    if WINDOWS:
        warn_legacy_startup()
    if paths.installed():
        stop(paths, settings_port(paths))
    if port_busy(port):
        if healthy(port):
            fail("another SearXNG already answers at http://127.0.0.1:%d. Stop it first, or install on another "
                 "port: python searxng_setup.py --port 8888" % port)
        fail("port %d is taken by another program; choose another one with --port" % port)
    python = find_python()
    os.makedirs(paths.root, exist_ok=True)
    with open(paths.marker, "w", encoding="utf-8") as f:  # lets uninstall delete this folder safely
        json.dump({"installer": "searxng_setup.py", "port": port, "updated": time.strftime("%Y-%m-%d %H:%M")}, f)
    if update or not os.path.isfile(os.path.join(paths.src, "searx", "webapp.py")):
        install_source(paths)
    install_venv(paths, python)
    write_settings(paths, port, explicit_port)
    write_launcher(paths)
    if autostart:
        autostart_enable(paths)
    elif autostart_enabled(paths):
        autostart_disable(paths)
        note("autostart disabled")
    say("Starting SearXNG")
    start(paths, port)
    verify(port)
    say("Done")
    srchplex_hint(port)


def cmd_status(paths):
    port = settings_port(paths)
    up = healthy(port)
    print("SearXNG for srchplex")
    print("  folder:     %s (%s)" % (paths.root, "installed" if paths.installed() else "not installed"))
    if paths.installed():
        print("  version:    %s" % read_version(paths))
    print("  autostart:  %s" % ("on" if autostart_enabled(paths) else "off"))
    print("  address:    http://127.0.0.1:%d (%s)" % (port, "running" if up else "not running"))
    if up:
        try:
            count, engines, blocked = test_search(port)
            print("  JSON:       %d results%s" % (count, (" from " + ", ".join(engines[:6])) if engines else ""))
            if blocked:
                print("  blocked:    " + ", ".join(blocked[:6]))
        except Exception as e:  # noqa: BLE001
            print("  JSON:       error: %s" % e)
    if port != DEFAULT_PORT:
        srchplex_hint(port)


def cmd_uninstall(paths, assume_yes):
    exists = os.path.isdir(paths.root)
    has_autostart = autostart_enabled(paths)
    if not exists and not has_autostart:
        print("Nothing to remove: %s does not exist." % paths.root)
        return
    if exists and not _is_ours(paths):
        # a mistyped --dir must not cost data: delete nothing from a folder this script did not install into
        if has_autostart:
            autostart_disable(paths)
            note("removed the autostart entry for %s" % paths.root)
        fail("nothing deleted: %s does not look like an installation made by searxng_setup.py "
             "(no install.json and no run.py from this script)" % paths.root)
    if not assume_yes:
        answer = input("Stop SearXNG, remove its autostart and delete the files it installed in %s? [y/N] "
                       % paths.root).strip().lower()
        if answer not in ("y", "yes"):
            print("Cancelled.")
            return
    say("Stopping SearXNG")
    stop(paths, settings_port(paths))
    autostart_disable(paths)
    if exists:
        say("Deleting the installed files from %s" % paths.root)
        for name in _OWN_ENTRIES:
            target = os.path.join(paths.root, name)
            if os.path.isdir(target) and not os.path.islink(target):
                shutil.rmtree(target, onerror=_force_remove)
            elif os.path.lexists(target):
                os.remove(target)
        left = _foreign_entries(paths)
        if left:
            note("kept %s: it also holds files the installer did not create (%s)"
                 % (paths.root, ", ".join(left[:5]) + (", …" if len(left) > 5 else "")))
        else:
            for name in _OS_JUNK:
                junk = os.path.join(paths.root, name)
                if os.path.isfile(junk):
                    os.remove(junk)
            try:
                os.rmdir(paths.root)
            except OSError as e:
                note("could not delete the empty folder %s: %s" % (paths.root, e))
    say("Removed. srchplex keeps working with its built-in sources.")


def _force_remove(func, path, _exc):
    os.chmod(path, stat.S_IWRITE)  # read-only files on Windows
    func(path)


def main():
    ap = argparse.ArgumentParser(prog="searxng_setup.py",
                                 description="Install and run SearXNG for the srchplex MCP server (one command).")
    ap.add_argument("command", nargs="?", default="install",
                    choices=["install", "status", "start", "stop", "restart", "update", "uninstall"])
    ap.add_argument("--port", type=int, help="port on 127.0.0.1 (default 8080, the srchplex default)")
    ap.add_argument("--dir", default=default_dir(), help="installation folder, new or empty (default: %(default)s)")
    ap.add_argument("--no-autostart", action="store_true", help="do not start SearXNG at login")
    ap.add_argument("-y", "--yes", action="store_true", help="uninstall without asking")
    a = ap.parse_args()
    paths = Paths(a.dir)
    port = a.port or settings_port(paths)
    if a.command == "install":
        cmd_install(paths, port, bool(a.port), autostart=not a.no_autostart)
    elif a.command == "update":
        if not paths.installed():
            fail("SearXNG is not installed in %s; run: python searxng_setup.py" % paths.root)
        cmd_install(paths, port, bool(a.port), autostart=autostart_enabled(paths) and not a.no_autostart, update=True)
    elif a.command == "status":
        cmd_status(paths)
    elif a.command == "uninstall":
        cmd_uninstall(paths, a.yes)
    else:
        if not paths.installed():
            fail("SearXNG is not installed in %s; run: python searxng_setup.py" % paths.root)
        if a.command in ("stop", "restart"):
            say("Stopping SearXNG")
            if not stop(paths, port):
                note("still answering at http://127.0.0.1:%d: that instance is not managed by this script" % port)
            elif a.command == "stop":
                note("stopped%s" % (" until the next login" if autostart_enabled(paths) else ""))
        if a.command in ("start", "restart"):
            say("Starting SearXNG")
            start(paths, port)


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        print("\nInterrupted.")
        sys.exit(130)
