def _suffix(paths):
    """The default folder gets the plain names; any other --dir gets its own, so installs never touch each other."""
    if os.path.normcase(paths.root) == os.path.normcase(os.path.abspath(default_dir())):
        return ""
    return "." + hashlib.sha1(os.path.normcase(paths.root).encode("utf-8")).hexdigest()[:8]


def _label(paths):
    return LABEL + _suffix(paths)


def _run_value(paths):
    return RUN_VALUE + _suffix(paths).replace(".", " ")


def _plist(paths):
    return os.path.expanduser("~/Library/LaunchAgents/%s.plist" % _label(paths))


def _launchd_target(paths):
    return "gui/%d/%s" % (os.getuid(), _label(paths))


def _launchd_loaded(paths):
    res = subprocess.run(["launchctl", "print", _launchd_target(paths)], stdout=DEVNULL, stderr=DEVNULL)
    return res.returncode == 0


def _launchd_load(paths):
    message = ""
    for _ in range(5):  # right after bootout launchd may still be tearing the job down
        res = subprocess.run(["launchctl", "bootstrap", "gui/%d" % os.getuid(), _plist(paths)],
                             stdout=subprocess.PIPE, stderr=subprocess.STDOUT, encoding="utf-8", errors="replace")
        if res.returncode == 0 or _launchd_loaded(paths):
            return
        message = res.stdout.strip()
        time.sleep(1)
    fail("launchctl bootstrap failed: %s" % message)


def _launchd_unload(paths):
    if _launchd_loaded(paths):
        subprocess.run(["launchctl", "bootout", _launchd_target(paths)], stdout=DEVNULL, stderr=DEVNULL)
        wait_until(lambda: not _launchd_loaded(paths), 10)


def _win_run_key(access):
    import winreg  # noqa: WPS433 — Windows only
    return winreg.OpenKey(winreg.HKEY_CURRENT_USER, RUN_KEY, 0, access)


def autostart_enabled(paths):
    if MACOS:
        return os.path.exists(_plist(paths))
    if WINDOWS:
        import winreg  # noqa: WPS433 — Windows only
        try:
            with _win_run_key(winreg.KEY_READ) as key:
                winreg.QueryValueEx(key, _run_value(paths))
            return True
        except OSError:
            return False
    return False


def autostart_enable(paths):
    if MACOS:
        os.makedirs(os.path.dirname(_plist(paths)), exist_ok=True)
        job = {"Label": _label(paths), "ProgramArguments": [paths.python(), paths.launcher],
               "WorkingDirectory": paths.root,
               "RunAtLoad": True, "KeepAlive": {"SuccessfulExit": False},  # restart after a crash only
               "StandardOutPath": paths.log, "StandardErrorPath": paths.log}
        with open(_plist(paths), "wb") as f:
            plistlib.dump(job, f)
        note("autostart: LaunchAgent %s" % _plist(paths))
    elif WINDOWS:
        import winreg  # noqa: WPS433 — Windows only
        command = '"%s" "%s"' % (paths.python(windowless=True), paths.launcher)
        with _win_run_key(winreg.KEY_SET_VALUE) as key:
            winreg.SetValueEx(key, _run_value(paths), 0, winreg.REG_SZ, command)
        note("autostart: HKCU\\%s, value \"%s\" (no console window)" % (RUN_KEY, _run_value(paths)))
    else:
        note("autostart is not set up on Linux: add `%s %s` to your session startup" % (paths.python(), paths.launcher))


def autostart_disable(paths):
    if MACOS:
        _launchd_unload(paths)
        if os.path.exists(_plist(paths)):
            os.remove(_plist(paths))
    elif WINDOWS:
        import winreg  # noqa: WPS433 — Windows only
        try:
            with _win_run_key(winreg.KEY_SET_VALUE) as key:
                winreg.DeleteValue(key, _run_value(paths))
        except OSError:
            pass


def warn_legacy_startup():
    """A manual install may start SearXNG from the Startup folder; two instances would fight for the port."""
    folder = os.path.join(os.environ.get("APPDATA", ""), "Microsoft", "Windows", "Start Menu", "Programs", "Startup")
    try:
        names = [n for n in os.listdir(folder) if "searx" in n.lower()]
    except OSError:
        return
    if names:
        note("note: the Startup folder also starts SearXNG (%s); remove it to keep one instance" % ", ".join(names))


