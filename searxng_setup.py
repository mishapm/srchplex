def find_python():
    """A Python 3.10+ interpreter for SearXNG: this one, or another found on PATH (py launcher on Windows)."""
    if sys.version_info >= (3, 10):
        return sys.executable
    candidates = [["py", "-3"]] if WINDOWS else []
    for name in ("python3.14", "python3.13", "python3.12", "python3.11", "python3.10", "python3", "python"):
        exe = shutil.which(name)
        if exe:
            candidates.append([exe])
    probe = "import sys; print(sys.executable); print(sys.version_info >= (3, 10))"
    for cmd in candidates:
        try:
            res = subprocess.run(cmd + ["-c", probe], stdout=subprocess.PIPE, stderr=DEVNULL, encoding="utf-8",
                                 errors="replace", timeout=30)
        except (OSError, subprocess.TimeoutExpired):
            continue
        lines = res.stdout.strip().splitlines()
        if res.returncode == 0 and len(lines) == 2 and lines[1] == "True":
            return lines[0]
    fail("SearXNG needs Python 3.10 or newer; install it from https://www.python.org/downloads/ and run again")


def load_windows_roots(ctx):
    """Add the Windows AuthRoot store (and certifi) to ctx; returns how many certificates were added.

    Python loads only the ROOT and CA stores. Windows fills ROOT lazily (and fetches missing intermediates
    via AIA), so newer roots such as Certainly Root R1 are often only in AuthRoot, and OpenSSL fails with
    CERTIFICATE_VERIFY_FAILED where a browser works.
    """
    added = 0
    for name in ("AuthRoot",):
        try:
            entries = ssl.enum_certificates(name)  # noqa: WPS437 — Windows only
        except Exception:  # noqa: BLE001
            continue
        for cert, encoding, trust in entries:
            if encoding != "x509_asn" or not (trust is True or ssl.Purpose.SERVER_AUTH.oid in trust):
                continue
            try:
                ctx.load_verify_locations(cadata=cert)
                added += 1
            except (ssl.SSLError, ValueError):
                continue
    try:
        import certifi  # noqa: WPS433 — optional dependency
        ctx.load_verify_locations(cafile=certifi.where())
        added += 1
    except Exception:  # noqa: BLE001
        pass
    return added


def ssl_context():
    """Fallback root certificates: the python.org build on macOS may not see the system ones."""
    ctx = ssl.create_default_context()
    if os.environ.get("SSL_CERT_FILE"):
        return ctx
    if WINDOWS:
        load_windows_roots(ctx)
        return ctx
    paths = ssl.get_default_verify_paths()
    if (paths.cafile and os.path.exists(paths.cafile)) or (
            paths.capath and os.path.isdir(paths.capath) and os.listdir(paths.capath)):
        return ctx
    candidates = []
    try:
        import certifi  # noqa: WPS433 — optional dependency
        candidates.append(certifi.where())
    except Exception:  # noqa: BLE001
        pass
    for path in candidates + ["/etc/ssl/cert.pem", "/etc/ssl/certs/ca-certificates.crt",
                              "/etc/pki/tls/certs/ca-bundle.crt"]:
        if path and os.path.exists(path):
            try:
                ctx.load_verify_locations(cafile=path)
                break
            except (OSError, ssl.SSLError):
                continue
    return ctx


def download(url, dest):
    opener = urllib.request.build_opener(urllib.request.HTTPSHandler(context=ssl_context()))
    req = urllib.request.Request(url, headers={"User-Agent": "searxng_setup.py (srchplex MCP)"})
    try:
        with opener.open(req, timeout=60) as r, open(dest, "wb") as f:
            shutil.copyfileobj(r, f, 1 << 20)
    except (urllib.error.URLError, OSError) as e:
        fail("cannot download %s: %s" % (url, getattr(e, "reason", e)))
    return os.path.getsize(dest)


_BAD_CHARS = re.compile(r'[<>:"|?*\x00-\x1f\\]')
_RESERVED = {"CON", "PRN", "AUX", "NUL"} | {"COM%d" % i for i in range(1, 10)} | {"LPT%d" % i for i in range(1, 10)}


def _valid_part(part):
    """A path component every OS can create (Windows forbids ':' and friends, which a few nginx templates use)."""
    return (part not in ("", ".", "..") and not _BAD_CHARS.search(part) and not part.endswith((" ", "."))
            and part.split(".")[0].upper() not in _RESERVED)


def extract(zip_path, dest):
    """Unpack the GitHub archive into dest -> (commit, commit date, skipped entries)."""
    skipped = 0
    with zipfile.ZipFile(zip_path) as z:
        commit = z.comment.decode("ascii", "ignore").strip()  # GitHub stores the commit hash here
        infos = z.infolist()
        root = infos[0].filename.split("/")[0] + "/"
        date_time = z.getinfo(root).date_time if root in z.namelist() else time.localtime()[:6]
        for info in infos:
            if not info.filename.startswith(root) or info.filename == root:
                continue
            parts = info.filename[len(root):].rstrip("/").split("/")
            if stat.S_ISLNK(info.external_attr >> 16) or not all(_valid_part(p) for p in parts):
                skipped += 1  # only deployment templates outside the searx package
                continue
            target = os.path.join(dest, *parts)
            if info.filename.endswith("/"):
                os.makedirs(target, exist_ok=True)
                continue
            os.makedirs(os.path.dirname(target), exist_ok=True)
            with z.open(info) as src, open(target, "wb") as out:
                shutil.copyfileobj(src, out)
    return commit, date_time, skipped


def freeze_version(src, commit, date_time):
    """searx/version.py asks git for the version; an archive has no git checkout, so freeze it instead."""
    version = "%04d.%02d.%02d+%s" % (date_time[0], date_time[1], date_time[2], commit[:7] or "unknown")
    code = ("# Generated by searxng_setup.py: the version of the downloaded archive (no git checkout).\n"
            'VERSION_STRING = "%s"\nVERSION_TAG = "%s"\nDOCKER_TAG = "%s"\n'
            'GIT_URL = "https://github.com/searxng/searxng"\nGIT_BRANCH = "master"\n'
            % (version, version, version.replace("+", "-")))
    with open(os.path.join(src, "searx", "version_frozen.py"), "w", encoding="utf-8") as f:
        f.write(code)
    return version


def latest_commit():
    """The latest commit of SearXNG master from the GitHub API, or None when GitHub cannot be reached."""
    opener = urllib.request.build_opener(urllib.request.HTTPSHandler(context=ssl_context()))
    req = urllib.request.Request(COMMIT_URL, headers={"User-Agent": "searxng_setup.py (srchplex MCP)",
                                                      "Accept": "application/vnd.github.sha"})
    try:
        with opener.open(req, timeout=30) as r:
            sha = r.read(200).decode("ascii", "ignore").strip()
    except (urllib.error.URLError, OSError, ValueError):
        return None
    return sha if re.match(r"^[0-9a-f]{40}$", sha) else None


def fetch_source(paths):
    """Download and unpack the latest SearXNG into src.new, next to the running one -> (commit, version)."""
    say("Downloading SearXNG from GitHub")
    fd, archive = tempfile.mkstemp(suffix=".zip")
    os.close(fd)
    new = paths.src + ".new"
    try:
        size = download(ARCHIVE_URL, archive)
        shutil.rmtree(new, ignore_errors=True)
        commit, date_time, skipped = extract(archive, new)
    finally:
        os.remove(archive)
    if not os.path.isfile(os.path.join(new, "searx", "webapp.py")):
        shutil.rmtree(new, ignore_errors=True)
        fail("the archive has no searx/webapp.py; the SearXNG repository layout has changed")
    version = freeze_version(new, commit, date_time)
    note("version %s, %.1f MB%s" % (version, size / 1e6,
                                     (", skipped %d server templates it does not need" % skipped) if skipped else ""))
    return commit, version


def install_source(paths):
    """A fresh install or a repair: the downloaded SearXNG replaces src/ right away."""
    commit, version = fetch_source(paths)
    new, old = paths.src + ".new", paths.src + ".old"
    shutil.rmtree(old, ignore_errors=True)
    if os.path.exists(paths.src):
        os.replace(paths.src, old)
    os.replace(new, paths.src)
    shutil.rmtree(old, ignore_errors=True)
    write_state(paths, commit=commit, version=version)


def install_venv(paths, python):
    if not os.path.isfile(paths.python()):
        say("Creating a virtual environment")
        run([python, "-m", "venv", paths.venv])
    say("Installing the SearXNG dependencies (a minute or two the first time)")
    pip = [paths.python(), "-m", "pip", "install", "--disable-pip-version-check", "--quiet"]
    run(pip + ["--upgrade", "pip"])
    run(pip + ["-r", os.path.join(paths.src, "requirements.txt")])


def write_settings(paths, port, explicit_port):
    if not os.path.exists(paths.settings):
        with open(paths.settings, "w", encoding="utf-8") as f:
            f.write(SETTINGS_TEMPLATE.format(port=port, secret=secrets.token_hex(32)))
        note("settings: %s" % paths.settings)
    elif explicit_port and settings_port(paths) != port:
        with open(paths.settings, encoding="utf-8") as f:
            text = f.read()
        with open(paths.settings, "w", encoding="utf-8") as f:
            f.write(re.sub(r"^(\s+port:\s*)\d+", r"\g<1>%d" % port, text, count=1, flags=re.M))
        note("port changed to %d in %s" % (port, paths.settings))


def write_launcher(paths):
    with open(paths.launcher, "w", encoding="utf-8") as f:
        f.write(LAUNCHER)


# --------------------------------------------------------------------------- #
# Autostart: LaunchAgent (macOS), HKCU Run value (Windows)
# --------------------------------------------------------------------------- #

def _suffix(paths):
    """The default folder gets the plain names; any other --dir gets its own, so installs never touch each other."""
    if os.path.normcase(paths.root) == os.path.normcase(os.path.abspath(default_dir())):
        return ""
    return "." + hashlib.sha1(os.path.normcase(paths.root).encode("utf-8")).hexdigest()[:8]


def _label(paths):
    return LABEL + _suffix(paths)


def _run_value(paths):
    return RUN_VALUE + _suffix(paths).replace(".", " ")


def _update_label(paths):
    return LABEL + ".update" + _suffix(paths)


def _plist(paths, label=None):
    return os.path.expanduser("~/Library/LaunchAgents/%s.plist" % (label or _label(paths)))


def _launchd_target(paths, label=None):
    return "gui/%d/%s" % (os.getuid(), label or _label(paths))


def _launchd_loaded(paths, label=None):
    res = subprocess.run(["launchctl", "print", _launchd_target(paths, label)], stdout=DEVNULL, stderr=DEVNULL)
    return res.returncode == 0


def _launchd_load(paths, label=None):
    message = ""
    for _ in range(5):  # right after bootout launchd may still be tearing the job down
        res = subprocess.run(["launchctl", "bootstrap", "gui/%d" % os.getuid(), _plist(paths, label)],
                             stdout=subprocess.PIPE, stderr=subprocess.STDOUT, encoding="utf-8", errors="replace")
        if res.returncode == 0 or _launchd_loaded(paths, label):
            return
        message = res.stdout.strip()
        time.sleep(1)
    fail("launchctl bootstrap failed: %s" % message)


def _launchd_unload(paths, label=None):
    if _launchd_loaded(paths, label):
        subprocess.run(["launchctl", "bootout", _launchd_target(paths, label)], stdout=DEVNULL, stderr=DEVNULL)
        wait_until(lambda: not _launchd_loaded(paths, label), 10)


def _win_run_key(access):
    import winreg  # noqa: WPS433 — Windows only
    return winreg.OpenKey(winreg.HKEY_CURRENT_USER, RUN_KEY, 0, access)


def autostart_enabled(paths):
    if MACOS:
        return os.path.exists(_plist(paths))
    if WINDOWS:
        import winreg  # noqa: WPS433 — Windows only
        try:
            with _win_run_key(winreg.KEY_READ) as key:
                winreg.QueryValueEx(key, _run_value(paths))
            return True
        except OSError:
            return False
    return False


def autostart_enable(paths):
    if MACOS:
        os.makedirs(os.path.dirname(_plist(paths)), exist_ok=True)
        job = {"Label": _label(paths), "ProgramArguments": [paths.python(), paths.launcher],
               "WorkingDirectory": paths.root,
               "RunAtLoad": True, "KeepAlive": {"SuccessfulExit": False},  # restart after a crash only
               "StandardOutPath": paths.log, "StandardErrorPath": paths.log}
        with open(_plist(paths), "wb") as f:
            plistlib.dump(job, f)
        note("autostart: LaunchAgent %s" % _plist(paths))
    elif WINDOWS:
        import winreg  # noqa: WPS433 — Windows only
        command = '"%s" "%s"' % (paths.python(windowless=True), paths.launcher)
        with _win_run_key(winreg.KEY_SET_VALUE) as key:
            winreg.SetValueEx(key, _run_value(paths), 0, winreg.REG_SZ, command)
        note("autostart: HKCU\\%s, value \"%s\" (no console window)" % (RUN_KEY, _run_value(paths)))
    else:
        note("autostart is not set up on Linux: add `%s %s` to your session startup" % (paths.python(), paths.launcher))


def autostart_disable(paths):
    if MACOS:
        _launchd_unload(paths)
        if os.path.exists(_plist(paths)):
            os.remove(_plist(paths))
    elif WINDOWS:
        import winreg  # noqa: WPS433 — Windows only
        try:
            with _win_run_key(winreg.KEY_SET_VALUE) as key:
                winreg.DeleteValue(key, _run_value(paths))
        except OSError:
            pass


def warn_legacy_startup():
    """A manual install may start SearXNG from the Startup folder; two instances would fight for the port."""
    folder = os.path.join(os.environ.get("APPDATA", ""), "Microsoft", "Windows", "Start Menu", "Programs", "Startup")
    try:
        names = [n for n in os.listdir(folder) if "searx" in n.lower()]
    except OSError:
        return
    if names:
        note("note: the Startup folder also starts SearXNG (%s); remove it to keep one instance" % ", ".join(names))


# --------------------------------------------------------------------------- #
# Automatic updates: a LaunchAgent (macOS) or a Task Scheduler task (Windows) runs `update --auto` once a day
# and after login; the update itself happens at most once a week (UPDATE_INTERVAL)
# --------------------------------------------------------------------------- #

def _task_name(paths):
    return UPDATE_TASK + _suffix(paths).replace(".", " ")


def update_command(paths, python):
    """The scheduled command. It runs the system Python, not the venv: the update moves the venv aside, and on
    Windows a folder with a running python.exe cannot be moved. pythonw.exe keeps the console window away."""
    if WINDOWS:
        windowless = os.path.join(os.path.dirname(python), "pythonw.exe")
        python = windowless if os.path.isfile(windowless) else python
    return [python, paths.setup, "update", "--auto", "--dir", paths.root]


def _update_job(paths, python):
    return {"Label": _update_label(paths), "ProgramArguments": update_command(paths, python),
            "WorkingDirectory": paths.root,
            "RunAtLoad": True,  # after login too: a Mac that is off at noon still gets its check
            "StartCalendarInterval": {"Hour": 12, "Minute": 0},  # missed while asleep: runs on wake
            "ProcessType": "Background", "LowPriorityIO": True,
            "StandardOutPath": paths.update_log, "StandardErrorPath": paths.update_log}


def _update_task_xml(paths, python):
    cmd = update_command(paths, python)
    args = " ".join('"%s"' % a if (" " in a or not a) else a for a in cmd[1:])
    return """<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo><Description>Daily check for SearXNG updates (srchplex); updates at most once a week</Description></RegistrationInfo>
  <Triggers>
    <CalendarTrigger>
      <StartBoundary>2026-01-01T12:00:00</StartBoundary>
      <Enabled>true</Enabled>
      <ScheduleByDay><DaysInterval>1</DaysInterval></ScheduleByDay>
    </CalendarTrigger>
  </Triggers>
  <Principals><Principal id="Author"><LogonType>InteractiveToken</LogonType><RunLevel>LeastPrivilege</RunLevel></Principal></Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <StartWhenAvailable>true</StartWhenAvailable>
    <RunOnlyIfNetworkAvailable>true</RunOnlyIfNetworkAvailable>
    <ExecutionTimeLimit>PT1H</ExecutionTimeLimit>
    <Enabled>true</Enabled>
  </Settings>
  <Actions Context="Author">
    <Exec>
      <Command>%s</Command>
      <Arguments>%s</Arguments>
      <WorkingDirectory>%s</WorkingDirectory>
    </Exec>
  </Actions>
</Task>
""" % (xml_escape(cmd[0]), xml_escape(args), xml_escape(paths.root))


def autoupdate_enabled(paths):
    if MACOS:
        return os.path.exists(_plist(paths, _update_label(paths)))
    if WINDOWS:
        res = subprocess.run(["schtasks", "/Query", "/TN", _task_name(paths)], stdout=DEVNULL, stderr=DEVNULL)
        return res.returncode == 0
    return False


def install_self(paths):
    """Copy this script into the installation: the scheduled update must not depend on where it was run from."""
    here = os.path.abspath(__file__)
    if os.path.normcase(here) != os.path.normcase(paths.setup):
        shutil.copyfile(here, paths.setup)


def autoupdate_enable(paths, python):
    install_self(paths)
    if MACOS:
        label = _update_label(paths)
        _launchd_unload(paths, label)
        with open(_plist(paths, label), "wb") as f:
            plistlib.dump(_update_job(paths, python), f)
        _launchd_load(paths, label)
        note("automatic updates: LaunchAgent %s (daily check at 12:00 and after login, an update at most "
             "once a week)" % _plist(paths, label))
    elif WINDOWS:
        fd, xml = tempfile.mkstemp(suffix=".xml")
        os.close(fd)
        try:
            with open(xml, "w", encoding="utf-16") as f:
                f.write(_update_task_xml(paths, python))
            run(["schtasks", "/Create", "/TN", _task_name(paths), "/XML", xml, "/F"])
        finally:
            os.remove(xml)
        note("automatic updates: Task Scheduler task \"%s\" (daily check, an update at most once a week)"
             % _task_name(paths))
    else:
        note("automatic updates are not scheduled on Linux: add to crontab (crontab -e):  0 12 * * *  %s"
             % " ".join('"%s"' % a for a in update_command(paths, python)))


def autoupdate_disable(paths):
    if MACOS:
        label = _update_label(paths)
        _launchd_unload(paths, label)
        if os.path.exists(_plist(paths, label)):
            os.remove(_plist(paths, label))
    elif WINDOWS and autoupdate_enabled(paths):
        subprocess.run(["schtasks", "/Delete", "/TN", _task_name(paths), "/F"], stdout=DEVNULL, stderr=DEVNULL)


