#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""One-command SearXNG for the srchplex MCP server: download, install, autostart, verify.

  python searxng_setup.py              install or repair, enable autostart, start and verify
  python searxng_setup.py status       installation, autostart, health and a test JSON search
  python searxng_setup.py start        start now
  python searxng_setup.py stop         stop until the next login (autostart stays enabled)
  python searxng_setup.py restart
  python searxng_setup.py update       download the latest SearXNG, keep the settings, restart
  python searxng_setup.py uninstall    stop, remove autostart and delete the installation

Options: --port N (default 8080), --dir PATH (a new or empty folder), --no-autostart, --yes (no confirmation
for uninstall). uninstall deletes only the files the installer created, and the folder itself once it is empty.

Works on macOS, Windows and Linux without Docker, git or administrator rights. Needs internet access and
Python 3.10+ for SearXNG itself; the script finds a suitable interpreter on its own. SearXNG listens on
127.0.0.1 only, with the JSON API enabled and the rate limiter off: it is meant for local use.

Everything lives in one folder:
  macOS    ~/Library/Application Support/searxng-srchplex
  Windows  %LOCALAPPDATA%\\searxng-srchplex
  Linux    ~/.local/share/searxng-srchplex
Autostart at login, per user: a LaunchAgent on macOS, the HKCU Run registry value on Windows.
On Linux the script starts SearXNG but does not set up autostart.
"""

