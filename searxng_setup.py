def _is_ours(paths):
    """The folder holds an installation made by this script: its install.json marker or its run.py."""
    try:
        with open(paths.marker, encoding="utf-8") as f:
            if json.load(f).get("installer") == "searxng_setup.py":
                return True
    except (OSError, ValueError, AttributeError):
        pass
    try:
        with open(paths.launcher, encoding="utf-8", errors="replace") as f:
            return _LAUNCHER_MARK in f.read(4000)
    except OSError:
        return False


def _foreign_entries(paths):
    """What else lies in the installation folder: files and folders this script did not create."""
    try:
        return sorted(n for n in os.listdir(paths.root) if n not in _OWN_ENTRIES and n not in _OS_JUNK)
    except OSError:
        return []


def _check_folder(paths):
    """Install only into a new or empty folder, or over an installation made by this script: SearXNG writes
    src/, venv/, run.py and settings.yml there and replaces an existing src/, so a folder with other files
    (a project, ~/Documents) would lose them."""
    if os.path.exists(paths.root) and not os.path.isdir(paths.root):
        fail("%s exists and is not a folder; choose another --dir" % paths.root)
    if not os.path.isdir(paths.root) or _is_ours(paths):
        return
    content = sorted(n for n in os.listdir(paths.root) if n not in _OS_JUNK)
    if content:
        fail("%s already contains files that this installer did not create (%s). SearXNG needs a new or empty "
             "folder: it writes src/, venv/, run.py and settings.yml there. Choose another one, for example "
             "--dir \"%s\"" % (paths.root, ", ".join(content[:5]) + (", …" if len(content) > 5 else ""),
                               os.path.join(paths.root, "searxng-srchplex")))


def run(cmd, **kw):
    res = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, encoding="utf-8",
                         errors="replace", **kw)
    if res.returncode != 0:
        tail = "\n".join(res.stdout.strip().splitlines()[-25:])
        fail("command failed: %s\n%s" % (" ".join(cmd), tail))
    return res.stdout


