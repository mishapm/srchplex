def _read_pid(paths):
    try:
        with open(paths.pid) as f:
            return int(f.read().strip())
    except (OSError, ValueError):
        return None


def _pid_is_ours(pid, paths):
    """Check the command line before killing: a stale PID file may point to an unrelated process by now."""
    if WINDOWS:
        query = "(Get-CimInstance Win32_Process -Filter 'ProcessId=%d').CommandLine" % pid
        try:
            out = subprocess.run(["powershell", "-NoProfile", "-Command", query], stdout=subprocess.PIPE,
                                 stderr=DEVNULL, encoding="utf-8", errors="replace", timeout=30).stdout
        except (OSError, subprocess.TimeoutExpired):
            return False
    else:
        out = subprocess.run(["ps", "-p", str(pid), "-o", "command="], stdout=subprocess.PIPE, stderr=DEVNULL,
                             encoding="utf-8", errors="replace").stdout
    return os.path.normcase(paths.launcher) in os.path.normcase(out)


def start(paths, port):
    if healthy(port):
        note("already running at http://127.0.0.1:%d" % port)
        return
    if MACOS and os.path.exists(_plist(paths)):
        if _launchd_loaded(paths):
            subprocess.run(["launchctl", "kickstart", _launchd_target(paths)], stdout=DEVNULL, stderr=DEVNULL)
        else:
            _launchd_load(paths)
    elif WINDOWS:
        flags = getattr(subprocess, "DETACHED_PROCESS", 0x8) | getattr(subprocess, "CREATE_NEW_PROCESS_GROUP", 0x200)
        subprocess.Popen([paths.python(windowless=True), paths.launcher], cwd=paths.root, creationflags=flags,
                         stdin=DEVNULL, stdout=DEVNULL, stderr=DEVNULL, close_fds=True)
    else:
        subprocess.Popen([paths.python(), paths.launcher], cwd=paths.root, start_new_session=True,
                         stdin=DEVNULL, stdout=DEVNULL, stderr=DEVNULL)
    if not wait_until(lambda: healthy(port), 90):
        fail("SearXNG did not answer on http://127.0.0.1:%d within 90 s. Log %s:\n%s"
             % (port, paths.log, log_tail(paths)))
    note("running at http://127.0.0.1:%d" % port)


def stop(paths, port):
    if MACOS:
        _launchd_unload(paths)
    pid = _read_pid(paths)
    if pid and _pid_is_ours(pid, paths):
        if WINDOWS:
            subprocess.run(["taskkill", "/PID", str(pid), "/T", "/F"], stdout=DEVNULL, stderr=DEVNULL)
        else:
            try:
                os.kill(pid, signal.SIGTERM)
                if not wait_until(lambda: not _pid_is_ours(pid, paths), 10):
                    os.kill(pid, getattr(signal, "SIGKILL", signal.SIGTERM))
            except OSError:
                pass
    if os.path.exists(paths.pid):
        try:
            os.remove(paths.pid)
        except OSError:
            pass
    wait_until(lambda: not healthy(port), 10)
    return not healthy(port)


