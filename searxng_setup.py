def wait_until(check, timeout):
    deadline = time.time() + timeout
    while time.time() < deadline:
        if check():
            return True
        time.sleep(0.5)
    return check()


def test_search(port):
    """A JSON search like the one srchplex sends -> (result count, engines that answered, blocked engines)."""
    url = "http://127.0.0.1:%d/search?q=python+programming+language&format=json" % port
    with _LOCAL.open(url, timeout=30) as r:
        data = json.loads(r.read().decode("utf-8"))
    results = data.get("results") or []
    engines = sorted({e for x in results for e in (x.get("engines") or [x.get("engine")]) if e})
    blocked = ["%s (%s)" % (e[0], e[1]) for e in data.get("unresponsive_engines") or [] if len(e) >= 2]
    return len(results), engines, blocked


def verify(port):
    try:
        count, engines, blocked = test_search(port)
    except urllib.error.HTTPError as e:
        if e.code == 403:
            fail("SearXNG refuses JSON: add json to search.formats in settings.yml and restart")
        fail("test search failed: HTTP %s" % e.code)
    except Exception as e:  # noqa: BLE001
        fail("test search failed: %s" % e)
    note("test search: %d results%s" % (count, (" from " + ", ".join(engines[:6])) if engines else ""))
    if blocked:
        note("blocked from this network right now (SearXNG pauses them by itself): " + ", ".join(blocked[:6]))
    if not count:
        note("no results yet: the engines may be rate-limiting this network; srchplex uses its built-in sources meanwhile")


