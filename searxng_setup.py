def say(message):
    print("==> " + message, flush=True)


def note(message):
    print("    " + message, flush=True)


def fail(message):
    print("ERROR: " + message, file=sys.stderr, flush=True)
    sys.exit(1)


def default_dir():
    if WINDOWS:
        base = os.environ.get("LOCALAPPDATA") or os.path.join(os.path.expanduser("~"), "AppData", "Local")
    elif MACOS:
        base = os.path.expanduser("~/Library/Application Support")
    else:
        base = os.environ.get("XDG_DATA_HOME") or os.path.expanduser("~/.local/share")
    return os.path.join(base, "searxng-srchplex")


class Paths(object):
    def __init__(self, root):
        self.root = os.path.abspath(os.path.expanduser(root))
        self.src = os.path.join(self.root, "src")
        self.venv = os.path.join(self.root, "venv")
        self.settings = os.path.join(self.root, "settings.yml")
        self.launcher = os.path.join(self.root, "run.py")
        self.log = os.path.join(self.root, "searxng.log")
        self.pid = os.path.join(self.root, "searxng.pid")
        self.marker = os.path.join(self.root, "install.json")

    def python(self, windowless=False):
        if WINDOWS:
            return os.path.join(self.venv, "Scripts", "pythonw.exe" if windowless else "python.exe")
        return os.path.join(self.venv, "bin", "python")

    def installed(self):
        return all(os.path.isfile(p) for p in (self.python(), self.launcher,
                                                os.path.join(self.src, "searx", "webapp.py")))


# What the installer creates in its folder; uninstall deletes these names and nothing else
_OWN_ENTRIES = ("src", "src.new", "src.old", "venv", "run.py", "settings.yml", "searxng.log", "searxng.log.1",
                "searxng.pid", "install.json")
_OS_JUNK = (".DS_Store", "Thumbs.db", "desktop.ini")  # files the OS file managers drop into folders
_LAUNCHER_MARK = "Generated by searxng_setup.py"  # in the docstring of the generated run.py


def _is_ours(paths):
    """The folder holds an installation made by this script: its install.json marker or its run.py."""
    try:
        with open(paths.marker, encoding="utf-8") as f:
            if json.load(f).get("installer") == "searxng_setup.py":
                return True
    except (OSError, ValueError, AttributeError):
        pass
    try:
        with open(paths.launcher, encoding="utf-8", errors="replace") as f:
            return _LAUNCHER_MARK in f.read(4000)
    except OSError:
        return False


def _foreign_entries(paths):
    """What else lies in the installation folder: files and folders this script did not create."""
    try:
        return sorted(n for n in os.listdir(paths.root) if n not in _OWN_ENTRIES and n not in _OS_JUNK)
    except OSError:
        return []


def _check_folder(paths):
    """Install only into a new or empty folder, or over an installation made by this script: SearXNG writes
    src/, venv/, run.py and settings.yml there and replaces an existing src/, so a folder with other files
    (a project, ~/Documents) would lose them."""
    if os.path.exists(paths.root) and not os.path.isdir(paths.root):
        fail("%s exists and is not a folder; choose another --dir" % paths.root)
    if not os.path.isdir(paths.root) or _is_ours(paths):
        return
    content = sorted(n for n in os.listdir(paths.root) if n not in _OS_JUNK)
    if content:
        fail("%s already contains files that this installer did not create (%s). SearXNG needs a new or empty "
             "folder: it writes src/, venv/, run.py and settings.yml there. Choose another one, for example "
             "--dir \"%s\"" % (paths.root, ", ".join(content[:5]) + (", …" if len(content) > 5 else ""),
                               os.path.join(paths.root, "searxng-srchplex")))


def run(cmd, **kw):
    res = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, encoding="utf-8",
                         errors="replace", **kw)
    if res.returncode != 0:
        tail = "\n".join(res.stdout.strip().splitlines()[-25:])
        fail("command failed: %s\n%s" % (" ".join(cmd), tail))
    return res.stdout


